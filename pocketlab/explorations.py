def list_explorations() -> list[ExplorationTemplate]:
    return [item.model_copy(deep=True) for item in EXPLORATION_CATALOG]


def exploration_ids_for_sensors(sensors: list[SensorKind]) -> list[str]:
    available = set(sensors)
    return [
        item.exploration_id
        for item in EXPLORATION_CATALOG
        if item.primary_sensor in available
    ]
