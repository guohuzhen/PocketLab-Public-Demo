def _template(
    exploration_id: str,
    title: str,
    question: str,
    category: str,
    primary_sensor: SensorKind,
    readiness: str,
    action_kind: str,
    readiness_note: str,
    duration_minutes: int,
    difficulty: str,
    protocol: list[str],
    expected_signal: str,
    output_value: str,
    *,
    safety_notes: list[str] | None = None,
    privacy_notes: list[str] | None = None,
    secondary_sensors: list[SensorKind] | None = None,
    executable_protocol_id: str | None = None,
    simulation_question: str | None = None,
    simulation_scope_note: str | None = None,
) -> ExplorationTemplate:
    return ExplorationTemplate(
        exploration_id=exploration_id,
        title=title,
        question=question,
        category=category,
        primary_sensor=primary_sensor,
        secondary_sensors=secondary_sensors or [],
        readiness=readiness,
        readiness_note=readiness_note,
        action_kind=action_kind,
        executable_protocol_id=executable_protocol_id,
        simulation_question=simulation_question,
        simulation_scope_note=simulation_scope_note,
        duration_minutes=duration_minutes,
        difficulty=difficulty,
        protocol=protocol,
        expected_signal=expected_signal,
        output_value=output_value,
        safety_notes=safety_notes or [],
        privacy_notes=privacy_notes or [],
        sources=_COMMON_SOURCES,
    )


